import re, sys, pathlib
d = pathlib.Path(sys.argv[1])
spec = (d / "spec.md").read_text()
acc = (d / "acceptance.md").read_text()
des = (d / "design.md").read_text()
reqs = re.findall(r"^\*\*REQ-AIR6-(\d+)\*\*", spec, re.M)
print("REQ count", len(reqs), "sequential", reqs == [f"{i:03d}" for i in range(1, len(reqs) + 1)])
acs = re.findall(r"^### AC-AIR6-(\d+) .*\(([^)]*)\)\s*$", acc, re.M)
print("AC count", len(acs), "sequential", [a for a, _ in acs] == [f"{i:03d}" for i in range(1, len(acs) + 1)])
cov = set()
for a, cited in acs:
    ids = re.findall(r"REQ-AIR6-(\d+)", cited)
    print("AC", a, "->", ids)
    cov.update(ids)
print("uncovered REQ:", sorted(set(reqs) - cov))
print("invalid REQ cited:", sorted(cov - set(reqs)))
rows = re.findall(r"^\| (\d+) \| `([a-z_]+)` \|", des, re.M)
print("design table rows", [r[0] for r in rows], len(rows))
sc = re.findall(r"^(\d+)\. `([a-z_]+)` ", spec, re.M)
print("spec conditions", [r[0] for r in sc], len(sc))
print("code lists equal (spec 1-17 vs design 1-17):", [r[1] for r in sc] == [r[1] for r in rows if r[0] != "0"])
for f in sorted(d.glob("*.md")):
    t = f.read_text()
    print(f.name, "has 0.3.1:", "0.3.1" in t, "stale 0.3.0 version line:", bool(re.search(r"버전 0\.3\.0|version: \"0\.3\.0\"", t)))
