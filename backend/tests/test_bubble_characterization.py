@pytest.mark.parametrize("market", MARKETS)
@pytest.mark.parametrize("period", PERIODS)
def test_bubble_matches_ranking_post_m4(client: Any, period: str, market: str) -> None:
    """M4 통일 후 — sectors[] 와 봉투 data[] 는 집합·4개 필드쌍 모두 일치한다.

    M0(pre-M4) 관측: 교집합 전 섹터·전 필드쌍 불일치 + bubble-only 별도 → N=18.
    뒤집힘: bubble-only 공집합, 집합 완전 일치, per_pair 전부 0 → N=0.
    """
    bubble = _get_bubble(client, period, market)
    ranking = _get_ranking(client, period, market)

    bmap = {s["name"]: s for s in bubble["sectors"]}
    dmap = {d["name"]: d for d in ranking["data"]}

    # pre-M4 bubble-only 는 사라졌다 — 이제 완전한 집합 일치(AG-5 를 양쪽 동일 적용).
    bubble_only = frozenset(bmap) - frozenset(dmap)
    assert bubble_only == frozenset(), (
        f"{period}/{market}: post-M4 bubble-only 가 공집합이 아니다: {sorted(bubble_only)}"
    )
    assert frozenset(dmap) == frozenset(bmap), (
        f"{period}/{market}: 봉투에만 있는 섹터 발견: "
        f"{sorted(frozenset(dmap) - frozenset(bmap))}"
    )

    per_pair = {"rs_avg": 0, "excess_return": 0, "trading_value": 0, "period_return": 0}
    mismatching: set[str] = set()
    detail: list[str] = []
    for name, b in bmap.items():
        d = dmap[name]
        pairs = {
            "rs_avg": (b["rs_avg"], d["rs_avg"]["value"]),
            "excess_return": (b["excess_return"], d["excess_returns"][period]["value"]),
            "trading_value": (b["trading_value"], d["trading_value"][period]["value"]),
            "period_return": (b["period_return"], d["returns"][period]["value"]),
        }
        for key, (bv, dv) in pairs.items():
            if _is_mismatch(bv, dv):
                per_pair[key] += 1
                mismatching.add(name)
                if len(detail) < 5:
                    detail.append(f"{name}.{key}: bubble={bv!r} envelope={dv!r}")

    assert not mismatching, (
        f"{period}/{market}: 4개 필드쌍 불일치 섹터 {len(mismatching)} — "
        f"per_pair={per_pair}\n" + "\n".join(detail)
    )
    for key, count in per_pair.items():
        assert count == 0, f"{period}/{market}: {key} 불일치 {count} != 0"

    # AC-SMU-015 관찰자 — post 집합은 M0 유니버스에서 AG-5 미달(pre-M4 bubble-only
    # 로 기록된 집합)만 뺀 집합과 정확히 일치한다.
    assert set(bmap) | PRE_M4_BUBBLE_ONLY[(period, market)] == set(M0_FULL_NAMES), (
        f"{period}/{market}: post-M4 섹터 집합이 M0 유니버스 - AG-5 미달 과 다르다: "
        f"대칭차={set(bmap) ^ (set(M0_FULL_NAMES) - PRE_M4_BUBBLE_ONLY[(period, market)])}"
    )


