def _assert_metric(got: Any, expected: Any, ctx: str) -> None:
    """None-None 일치, 한쪽만 None 불일치, 값이면 1e-6 근사."""
    if got is None or expected is None:
        assert got is expected, f"{ctx}: {got!r} != {expected!r}"
    else:
        assert got == pytest.approx(expected, abs=1e-6), f"{ctx}: {got!r} != {expected!r}"


@pytest.mark.parametrize("market", MARKETS)
@pytest.mark.parametrize("period", PERIODS)
def test_bubble_characterization_snapshot(client: Any, period: str, market: str) -> None:
    """9조합 각각에서 섹터명 집합과 4개 메트릭 post-M4 값을 리터럴에 고정한다."""
    body = _get_bubble(client, period, market)
    expected = EXPECTED[period][market]

    assert body["date"] == AS_OF
    assert body["as_of_date"] == AS_OF
    assert body["period"] == period
